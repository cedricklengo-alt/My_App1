/// Recherche instantanée (nom, indicatif, ISO — insensible aux accents).
List<Country> searchCountries(String q) {
  final n = _norm(q.trim());
  if (n.isEmpty) return kCountries;
  return kCountries
      .where((c) =>
          _norm(c.name).contains(n) ||
          c.dial.replaceAll('+', '').contains(n.replaceAll('+', '')) ||
          c.iso.toLowerCase().contains(n.toLowerCase()))
      .toList();
}

String _norm(String s) => s
    .toLowerCase()
    .replaceAll('é', 'e').replaceAll('è', 'e').replaceAll('ê', 'e').replaceAll('ë', 'e')
    .replaceAll('à', 'a').replaceAll('â', 'a').replaceAll('î', 'i').replaceAll('ô', 'o')
    .replaceAll('û', 'u').replaceAll('ç', 'c').replaceAll('ù', 'u');
