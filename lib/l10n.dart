/// 🗣️ MboteCall parle les langues de la RDC — et peut en télécharger d'autres.
/// Usage : L10n.t('topup')  ·  changement : L10n.setLang('ln')
/// Téléchargement : L10n.install('en', 'English 🇬🇧', {...})
class L10n {
  static String lang = 'fr';
  static final ValueNotifier<int> version = ValueNotifier(0);

  /// Langues intégrées
  static const Map<String, String> builtin = {
    'fr': 'Français 🇫🇷',
    'ln': 'Lingála 🇨🇩',
    'sw': 'Kiswahili 🇨🇩',
  };

  /// Langues téléchargées (code → nom) + leurs textes
  static final Map<String, String> _extraNames = {};
  static final Map<String, Map<String, String>> _extra = {};

  /// Toutes les langues installées
  static Map<String, String> get langs => {...builtin, ..._extraNames};

  static Future<void> load() async {
    final p = await SharedPreferences.getInstance();
    lang = p.getString('lang') ?? 'fr';
    // Langues téléchargées précédemment
    final names = p.getString('extra_lang_names');
    if (names != null) {
      final m = Map<String, dynamic>.from(jsonDecode(names));
      for (final e in m.entries) {
        final pack = p.getString('lang_pack_${e.key}');
        if (pack != null) {
          _extraNames[e.key] = e.value.toString();
          _extra[e.key] = Map<String, String>.from(jsonDecode(pack));
        }
      }
    }
    if (!langs.containsKey(lang)) lang = 'fr';
    version.value++;
  }

  static Future<void> setLang(String l) async {
    lang = l;
    (await SharedPreferences.getInstance()).setString('lang', l);
    version.value++; // notifie toute l'app
  }

  /// 📥 Installe une langue téléchargée depuis le serveur
  static Future<void> install(
      String code, String name, Map<String, String> strings) async {
    _extraNames[code] = name;
    _extra[code] = strings;
    final p = await SharedPreferences.getInstance();
    await p.setString('lang_pack_$code', jsonEncode(strings));
    await p.setString('extra_lang_names', jsonEncode(_extraNames));
    version.value++;
  }

  static String t(String key) =>
      _extra[lang]?[key] ?? _s[lang]?[key] ?? _s['fr']![key] ?? key;

  /// Toutes les clés DÉCLARÉES pour une langue (sans repli sur le français).
  /// Sert aux tests de contrat et aux écrans de réglages.
  static Set<String> keys(String lang) => {
        ...?_s[lang]?.keys,
        ...?_extra[lang]?.keys,
      };

  /// Traduction dans une langue donnée, avec le repli français.
  /// Contrairement à [t], ne dépend pas de la langue actuellement choisie.
  static String? t2(String lang, String key) =>
      _extra[lang]?[key] ?? _s[lang]?[key] ?? _s['fr']?[key];

  /// Traduction BRUTE : uniquement la langue demandée, sans repli.
  static String? raw(String lang, String key) =>
      _extra[lang]?[key] ?? _s[lang]?[key];

